/* A Unicode code point -> glyph index. Returns G_SPACE for anything not
 * present. */
static int font_glyph(uint32_t cp)
{
    if (cp >= '0' && cp <= '9') return G_0 + (int)(cp - '0');
    if (cp >= 'A' && cp <= 'Z') return G_A + (int)(cp - 'A');
    if (cp >= 'a' && cp <= 'z') return G_A + (int)(cp - 'a');
    switch (cp) {
        case ' ':    return G_SPACE;
        case '+':    return G_PLUS;
        case '-':    return G_MINUS;
        case '/':    return G_SLASH;
        case '.':    return G_DOT;
        case '?':    return G_QUERY;
        case '_':    return G_UNDER;
        /* Cyrillic letters whose shape matches a Latin one */
        case 0x0410: return G_A;      /* А */
        case 0x0412: return G_B;      /* В */
        case 0x0415: return G_E;      /* Е */
        case 0x041A: return G_K;      /* К */
        case 0x041C: return G_M;      /* М */
        case 0x041D: return G_H;      /* Н */
        case 0x041E: return G_O;      /* О */
        case 0x0420: return G_P;      /* Р */
        case 0x0421: return G_C;      /* С */
        case 0x0422: return G_T;      /* Т */
        case 0x0425: return G_X;      /* Х */
        /* Cyrillic letters with their own shape */
        case 0x0411: return G_BE;     /* Б */
        case 0x0413: return G_GHE;    /* Г */
        case 0x0414: return G_DE;     /* Д */
        case 0x0417: return G_ZE;     /* З */
        case 0x0418: case 0x0419: return G_I_CYR;  /* И, Й */
        case 0x041B: return G_EL;     /* Л */
        case 0x041F: return G_PE;     /* П */
        case 0x0423: return G_U_CYR;  /* У */
        case 0x0424: return G_EF;     /* Ф */
        case 0x0426: return G_TSE;    /* Ц */
        case 0x0427: return G_CHE;    /* Ч */
        case 0x0428: case 0x0429: return G_SHA;   /* Ш, Щ */
        case 0x042A: case 0x042C: return G_SOFT;  /* Ъ, Ь */
        case 0x042B: return G_YERY;   /* Ы */
        case 0x042D: return G_E_CYR;  /* Э */
        case 0x042F: return G_YA;     /* Я */
        default:     return G_SPACE;
    }
}

/* Decodes one UTF-8 character and advances the pointer. */
static uint32_t utf8_next(const char **p)
{
    const unsigned char *s = (const unsigned char *)*p;
    uint32_t cp;
    if (s[0] < 0x80u) { cp = s[0]; *p += 1; }
    else if ((s[0] & 0xE0u) == 0xC0u) {
        cp = (uint32_t)((s[0] & 0x1Fu) << 6) | (uint32_t)(s[1] & 0x3Fu);
        *p += 2;
    } else if ((s[0] & 0xF0u) == 0xE0u) {
        cp = (uint32_t)((s[0] & 0x0Fu) << 12) | (uint32_t)((s[1] & 0x3Fu) << 6)
           | (uint32_t)(s[2] & 0x3Fu);
        *p += 3;
    } else { cp = '?'; *p += 1; }
    return cp;
}

/* Pixel width of a string at scale `sc` (5 px of glyph + 1 of gap). */
static int font_width(const char *s, int sc)
{
    int n = 0;
    while (*s) { (void)utf8_next(&s); n++; }
    return n * 6 * sc - sc;
}

